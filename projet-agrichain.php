                            <h2>Présentation du projet</h2>
                            <p>INFINITIA AgriChain est une plateforme numérique qui digitalise la chaîne d’approvisionnement agricole, de la production jusqu’au marché. Elle connecte les producteurs, coopératives, transporteurs, entrepôts, acheteurs et consommateurs autour d’un système logistique intelligent.</p>

                            <h3>Problématique</h3>
                            <p>En République Démocratique du Congo, une grande partie des produits agricoles n’atteint jamais les marchés dans de bonnes conditions à cause du manque de traçabilité, des faibles capacités logistiques, des difficultés à trouver des transporteurs fiables, des pertes post-récolte et du manque d’informations sur les marchés.</p>

                            <h3>Solution proposée</h3>
                            <p>La plateforme permet d’enregistrer les producteurs, gérer les récoltes, organiser le transport, suivre les marchandises, connecter les vendeurs aux acheteurs et assurer la traçabilité des produits agricoles.</p>

                            <h3>Impact attendu</h3>
                            <p>INFINITIA AgriChain vise à rendre la logistique agricole plus productive, plus transparente, plus inclusive et plus durable.</p>

